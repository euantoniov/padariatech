-- Criação das tabelas produtos, vendas, itens_venda, índices, RLS e função transacional registrar_venda

-- 1. TABELA PRODUTOS
CREATE TABLE IF NOT EXISTS public.produtos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL,
    categoria VARCHAR(60) NOT NULL,
    preco NUMERIC(10,2) NOT NULL CHECK (preco > 0),
    estoque INTEGER NOT NULL CHECK (estoque >= 0),
    usuario_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- 2. TABELA VENDAS
CREATE TABLE IF NOT EXISTS public.vendas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data_venda TIMESTAMPTZ NOT NULL DEFAULT now(),
    valor_total NUMERIC(10,2) NOT NULL CHECK (valor_total >= 0),
    usuario_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE
);

-- 3. TABELA ITENS_VENDA
CREATE TABLE IF NOT EXISTS public.itens_venda (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    venda_id BIGINT NOT NULL REFERENCES public.vendas(id) ON DELETE CASCADE,
    produto_id BIGINT NOT NULL REFERENCES public.produtos(id) ON DELETE RESTRICT,
    quantidade INTEGER NOT NULL CHECK (quantidade > 0),
    preco_unitario NUMERIC(10,2) NOT NULL CHECK (preco_unitario > 0),
    subtotal NUMERIC(10,2) NOT NULL CHECK (subtotal >= 0)
);

-- 4. ÍNDICES DE PERFORMANCE E INTEGRIDADE
CREATE INDEX IF NOT EXISTS idx_produtos_usuario ON public.produtos(usuario_id);
CREATE INDEX IF NOT EXISTS idx_produtos_nome ON public.produtos(usuario_id, nome);
CREATE INDEX IF NOT EXISTS idx_vendas_usuario_data ON public.vendas(usuario_id, data_venda DESC);
CREATE INDEX IF NOT EXISTS idx_itens_venda_venda ON public.itens_venda(venda_id);
CREATE INDEX IF NOT EXISTS idx_itens_venda_produto ON public.itens_venda(produto_id);

-- 5. HABILITAR ROW LEVEL SECURITY (RLS)
ALTER TABLE public.produtos ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.vendas ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.itens_venda ENABLE ROW LEVEL SECURITY;

-- 6. POLÍTICAS DE RLS - TABELA PRODUTOS
DROP POLICY IF EXISTS "produtos_select_proprio" ON public.produtos;
CREATE POLICY "produtos_select_proprio" ON public.produtos
    FOR SELECT TO authenticated
    USING (auth.uid() = usuario_id);

DROP POLICY IF EXISTS "produtos_insert_proprio" ON public.produtos;
CREATE POLICY "produtos_insert_proprio" ON public.produtos
    FOR INSERT TO authenticated
    WITH CHECK (auth.uid() = usuario_id);

DROP POLICY IF EXISTS "produtos_update_proprio" ON public.produtos;
CREATE POLICY "produtos_update_proprio" ON public.produtos
    FOR UPDATE TO authenticated
    USING (auth.uid() = usuario_id)
    WITH CHECK (auth.uid() = usuario_id);

DROP POLICY IF EXISTS "produtos_delete_proprio" ON public.produtos;
CREATE POLICY "produtos_delete_proprio" ON public.produtos
    FOR DELETE TO authenticated
    USING (auth.uid() = usuario_id);

-- 7. POLÍTICAS DE RLS - TABELA VENDAS (Apenas leitura direta pelo dono; criação somente via RPC transacional)
DROP POLICY IF EXISTS "vendas_select_proprio" ON public.vendas;
CREATE POLICY "vendas_select_proprio" ON public.vendas
    FOR SELECT TO authenticated
    USING (auth.uid() = usuario_id);

-- 8. POLÍTICAS DE RLS - TABELA ITENS_VENDA (Leitura apenas de vendas do próprio usuário)
DROP POLICY IF EXISTS "itens_venda_select_proprio" ON public.itens_venda;
CREATE POLICY "itens_venda_select_proprio" ON public.itens_venda
    FOR SELECT TO authenticated
    USING (
        EXISTS (
            SELECT 1 FROM public.vendas v
            WHERE v.id = itens_venda.venda_id
              AND v.usuario_id = auth.uid()
        )
    );

-- 9. FUNÇÃO RPC TRANSACIONAL: REGISTRAR VENDA
-- Valida autenticação, verifica produtos e propriedade, bloqueia registros para concorrência (FOR UPDATE),
-- calcula total seguro no servidor, insere venda e itens, abate estoque e cancela tudo em caso de erro.
CREATE OR REPLACE FUNCTION public.registrar_venda(p_itens JSONB)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, auth, pg_temp
AS $$
DECLARE
    v_usuario_id UUID := auth.uid();
    v_venda_id BIGINT;
    v_valor_total NUMERIC(10,2) := 0;
    v_item JSONB;
    v_prod_id BIGINT;
    v_qtd INTEGER;
    v_preco NUMERIC(10,2);
    v_estoque INTEGER;
    v_subtotal NUMERIC(10,2);
BEGIN
    -- 1. Validar usuário autenticado
    IF v_usuario_id IS NULL THEN
        RAISE EXCEPTION 'Acesso não autorizado: usuário não autenticado.';
    END IF;

    -- 2. Validar carrinho não vazio
    IF p_itens IS NULL OR jsonb_array_length(p_itens) = 0 THEN
        RAISE EXCEPTION 'O carrinho não pode estar vazio.';
    END IF;

    -- 3. Primeira passagem: validar todos os itens, travar linhas (FOR UPDATE), verificar estoque e calcular total
    FOR v_item IN SELECT * FROM jsonb_array_elements(p_itens)
    LOOP
        v_prod_id := (v_item->>'produto_id')::BIGINT;
        v_qtd     := (v_item->>'quantidade')::INTEGER;

        IF v_prod_id IS NULL OR v_qtd IS NULL OR v_qtd <= 0 THEN
            RAISE EXCEPTION 'Dados de item inválidos ou quantidade não positiva.';
        END IF;

        -- Bloqueio pessimista para concorrência + validação de propriedade
        SELECT preco, estoque INTO v_preco, v_estoque
        FROM public.produtos
        WHERE id = v_prod_id AND usuario_id = v_usuario_id
        FOR UPDATE;

        IF NOT FOUND THEN
            RAISE EXCEPTION 'Produto (ID: %) não encontrado ou não pertence ao usuário.', v_prod_id;
        END IF;

        IF v_estoque < v_qtd THEN
            RAISE EXCEPTION 'Estoque insuficiente para o produto ID % (Estoque atual: %, Solicitado: %).', v_prod_id, v_estoque, v_qtd;
        END IF;

        v_subtotal := ROUND(v_preco * v_qtd, 2);
        v_valor_total := v_valor_total + v_subtotal;
    END LOOP;

    -- 4. Criar cabeçalho da venda
    INSERT INTO public.vendas (data_venda, valor_total, usuario_id)
    VALUES (now(), v_valor_total, v_usuario_id)
    RETURNING id INTO v_venda_id;

    -- 5. Segunda passagem: inserir itens da venda e abater estoque
    FOR v_item IN SELECT * FROM jsonb_array_elements(p_itens)
    LOOP
        v_prod_id := (v_item->>'produto_id')::BIGINT;
        v_qtd     := (v_item->>'quantidade')::INTEGER;

        SELECT preco INTO v_preco
        FROM public.produtos
        WHERE id = v_prod_id AND usuario_id = v_usuario_id;

        v_subtotal := ROUND(v_preco * v_qtd, 2);

        INSERT INTO public.itens_venda (venda_id, produto_id, quantidade, preco_unitario, subtotal)
        VALUES (v_venda_id, v_prod_id, v_qtd, v_preco, v_subtotal);

        UPDATE public.produtos
        SET estoque = estoque - v_qtd
        WHERE id = v_prod_id;
    END LOOP;

    -- 6. Retornar dados da venda registrada
    RETURN jsonb_build_object(
        'venda_id', v_venda_id,
        'valor_total', v_valor_total,
        'mensagem', 'Venda registrada com sucesso!'
    );
END;
$$;

-- Restringir permissões da função RPC
REVOKE ALL ON FUNCTION public.registrar_venda(JSONB) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.registrar_venda(JSONB) TO authenticated;
